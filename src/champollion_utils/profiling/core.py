"""Cross-process profiling runtime: per-process segments, sidecars and cProfile dumps.

Profiling is opt-in: nothing here runs unless CHAMPOLLION_PROFILE names a
profile dir. Each profiled process writes, per segment, a JSON sidecar and (in
mode cpu) a cProfile dump under ``<profile dir>/<run_id>/proc/``. Python
children are profiled through a generated ``sitecustomize.py`` boot dir put
first on PYTHONPATH.

This module is stdlib only and self-contained (no other champollion_utils
import, no relative import): the boot file loads it by absolute path in envs
where champollion_utils is not installed. It never writes to stdout.
"""

import atexit
import contextlib
import cProfile
import json
import logging
import os
import resource
import signal
import socket
import sys
import time
from collections.abc import Iterator, Mapping
from datetime import datetime, timezone
from pathlib import Path

ENV_PROFILE_DIR = "CHAMPOLLION_PROFILE"
ENV_PROFILE_MODE = "CHAMPOLLION_PROFILE_MODE"
ENV_PROFILE_RUN = "CHAMPOLLION_PROFILE_RUN_ID"
ENV_PROFILE_STAGE = "CHAMPOLLION_PROFILE_STAGE"
ENV_PROFILE_TAGS = "CHAMPOLLION_PROFILE_TAGS"
ENV_PROFILE_PARENT = "CHAMPOLLION_PROFILE_PARENT"
ENV_PROFILE_SAMPLER = "CHAMPOLLION_PROFILE_SAMPLER_PID"
ENV_PROFILE_INTERVAL = "CHAMPOLLION_PROFILE_INTERVAL_S"
ENV_PROFILE_GPU = "CHAMPOLLION_PROFILE_GPU"
MODES = ("cpu", "light")
DEFAULT_MODE = "cpu"
LOGGER_NAME = "champollion_utils.profiling"

# Module name under which the boot file loads this file; champollion_utils.profiling reuses it.
BOOT_MODULE_NAME = "_champollion_profiling_core"
SIDECAR_SCHEMA = 1
RUN_SCHEMA = 1

logger = logging.getLogger(LOGGER_NAME)

_BOOT_TEMPLATE = '''\
"""Profiling boot for one run, generated by champollion_utils.profiling. Stdlib only."""

import importlib.machinery
import importlib.util
import logging
import os
import sys

_CORE = {core!r}


def _boot():
    try:
        spec = importlib.util.spec_from_file_location({module!r}, _CORE)
        module = importlib.util.module_from_spec(spec)
        sys.modules[spec.name] = module
        spec.loader.exec_module(module)
        module.ensure_profiling_from_env()
    except Exception as error:  # profiling must never stop the interpreter
        record = logging.makeLogRecord(
            {{"msg": "profiling boot failed: %s", "args": (error,), "levelno": logging.WARNING, "levelname": "WARNING"}}
        )
        logging.lastResort.handle(record)


def _chain():
    here = os.path.dirname(os.path.abspath(__file__))
    entries = [entry or os.getcwd() for entry in sys.path]
    later = [entry for index, entry in enumerate(entries) if os.path.abspath(entry) != here and here in
             [os.path.abspath(previous) for previous in entries[:index]]]
    spec = importlib.machinery.PathFinder.find_spec("sitecustomize", later)
    if spec is None or spec.loader is None:
        return
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)


_boot()
_chain()
'''


class InvalidProfileMode(ValueError):
    """A profiling mode other than cpu or light (the empty string included)."""


class _Session:
    """Profiling state of this process; one instance, reset in forked children."""

    def __init__(self):
        self.result: bool | None = None
        self.mode = DEFAULT_MODE
        self.run_id = ""
        self.run_dir: Path | None = None
        self.root = False
        self.host = socket.gethostname()
        self.pid = 0
        self.seq = 0
        self.origin = "exec"
        self.segment: dict | None = None
        self.profiler: cProfile.Profile | None = None
        self.times: os.times_result | None = None
        self.t_start = 0.0
        self.warned = False
        self.closing = False
        self.pending_signal: int | None = None


_session = _Session()
_after_fork_token = type("_AfterForkToken", (), {})()


# ---------------------------------------------------------------------------
# Small public helpers
# ---------------------------------------------------------------------------


def resolve_mode(value: str | None) -> str:
    """Profiling mode of an env value: absent -> cpu; cpu or light -> itself; anything else is invalid."""
    if value is None:
        return DEFAULT_MODE
    if value in MODES:
        return value
    raise InvalidProfileMode(
        f"profiling mode must be one of {', '.join(MODES)}, got {value!r}"
    )


def is_profiling_enabled() -> bool:
    """True when this process has an open profiling session."""
    return _session.segment is not None


def new_run_id() -> str:
    """Run id ``<UTC %Y%m%dT%H%M%SZ>-<host>-<pid>``."""
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    return f"{stamp}-{socket.gethostname()}-{os.getpid()}"


def get_boot_dir(run_dir: Path) -> Path:
    """Boot dir of a run: ``<run_dir>/boot``."""
    return Path(run_dir) / "boot"


def write_boot_dir(run_dir: Path) -> Path:
    """Create the boot dir of ``run_dir`` with its sitecustomize.py (kept when already there); return the dir."""
    boot = get_boot_dir(run_dir)
    boot.mkdir(parents=True, exist_ok=True)
    target = boot / "sitecustomize.py"
    if not target.is_file():
        source = _BOOT_TEMPLATE.format(
            core=str(Path(__file__).resolve()), module=BOOT_MODULE_NAME
        )
        _write_atomic(target, source)
    return boot


def make_profiling_env(
    profile_dir: Path, mode: str, base_env: Mapping[str, str]
) -> dict[str, str]:
    """A copy of ``base_env`` that profiles the Python process started with it into ``profile_dir``."""
    if mode not in MODES:
        raise InvalidProfileMode(
            f"profiling mode must be one of {', '.join(MODES)}, got {mode!r}"
        )
    profile_dir = Path(profile_dir).absolute()
    env = dict(base_env)
    env[ENV_PROFILE_DIR] = str(profile_dir)
    env[ENV_PROFILE_MODE] = mode
    run_id = env.get(ENV_PROFILE_RUN) or new_run_id()
    env[ENV_PROFILE_RUN] = run_id
    env["PYTHONPATH"] = _prepend_path(
        str(write_boot_dir(profile_dir / run_id)), env.get("PYTHONPATH")
    )
    return env


# ---------------------------------------------------------------------------
# Files
# ---------------------------------------------------------------------------


def _write_atomic(path: Path, text: str) -> None:
    """Write ``text`` to ``path`` through a temporary file and os.replace."""
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def _prepend_path(entry: str, current: str | None) -> str:
    """``entry`` first on a PYTHONPATH value (not added again when already first)."""
    entries = [item for item in (current or "").split(os.pathsep) if item]
    if entries and entries[0] == entry:
        return os.pathsep.join(entries)
    return os.pathsep.join([entry, *entries])


def _parse_tags(value: str | None) -> dict[str, str]:
    """``key=value,key=value`` into a dict (malformed items are ignored)."""
    tags = {}
    for item in (value or "").split(","):
        key, sep, tag = item.partition("=")
        if sep and key.strip():
            tags[key.strip()] = tag.strip()
    return tags


def _format_tags(tags: Mapping[str, str]) -> str:
    return ",".join(f"{key}={value}" for key, value in tags.items())


def _segment_name(seq: int) -> str:
    return f"{_session.host}-{_session.pid}-{seq}"


def _write_run_json(t_end: float | None) -> None:
    run_json = {
        "schema": RUN_SCHEMA,
        "run_id": _session.run_id,
        "argv": list(sys.argv),
        "t_start": _session.t_start,
        "t_end": t_end,
        "mode": _session.mode,
        "hosts": [_session.host],
    }
    _write_atomic(_session.run_dir / "run.json", json.dumps(run_json, indent=2))


def _write_sidecar(segment: dict) -> None:
    _write_atomic(
        _session.run_dir / "proc" / f"{segment['name']}.json",
        json.dumps(segment["sidecar"], indent=2),
    )


# ---------------------------------------------------------------------------
# Segments
# ---------------------------------------------------------------------------


def _disable(reason: str) -> None:
    """Log the single profiling WARNING of this process and close the session without writing."""
    if not _session.warned:
        logger.warning(f"profiling disabled: {reason}")
        _session.warned = True
    if _session.profiler is not None:
        _session.profiler.disable()
    _session.profiler = None
    _session.segment = None


def _open_segment(stage: str, tags: Mapping[str, str], parent: str | None) -> None:
    """Start a new segment: sidecar written with complete false, profiler on in mode cpu."""
    seq = _session.seq
    _session.seq += 1
    name = _segment_name(seq)
    now = time.time()
    sidecar = {
        "schema": SIDECAR_SCHEMA,
        "run_id": _session.run_id,
        "host": _session.host,
        "pid": _session.pid,
        "ppid": os.getppid(),
        "seq": seq,
        "parent_segment": parent,
        "origin": _session.origin,
        "executable": sys.executable,
        "python_version": sys.version.split()[0],
        "argv": list(sys.argv),
        "cwd": os.getcwd(),
        "stage": stage,
        "tags": dict(tags),
        "mode": _session.mode,
        "t_start": now,
        "t_end": None,
        "wall_s": None,
        "cpu_user_s": None,
        "cpu_sys_s": None,
        "children_cpu_user_s": None,
        "children_cpu_sys_s": None,
        "maxrss_kb": None,
        "complete": False,
        "exit_path": None,
        "profile_file": f"{name}.prof" if _session.mode == "cpu" else None,
        "mem_file": None,
        "gpu": None,
    }
    segment = {"name": name, "sidecar": sidecar}
    _write_sidecar(segment)
    _session.segment = segment
    _session.times = os.times()
    os.environ[ENV_PROFILE_STAGE] = stage
    os.environ[ENV_PROFILE_PARENT] = name
    if tags:
        os.environ[ENV_PROFILE_TAGS] = _format_tags(tags)
    else:
        os.environ.pop(ENV_PROFILE_TAGS, None)
    if _session.mode == "cpu":
        _session.profiler = cProfile.Profile()
        _session.profiler.enable()


def _close_segment(exit_path: str) -> None:
    """End the open segment of this process: dump the profile and complete its sidecar (idempotent)."""
    segment = _session.segment
    if segment is None or segment["sidecar"]["pid"] != os.getpid():
        return
    _session.segment = None
    _session.closing = True
    profiler, _session.profiler = _session.profiler, None
    if profiler is not None:
        profiler.disable()
    try:
        end = os.times()
        start = _session.times
        sidecar = segment["sidecar"]
        sidecar["argv"] = list(sys.argv)
        sidecar["t_end"] = time.time()
        sidecar["wall_s"] = sidecar["t_end"] - sidecar["t_start"]
        sidecar["cpu_user_s"] = end.user - start.user
        sidecar["cpu_sys_s"] = end.system - start.system
        sidecar["children_cpu_user_s"] = end.children_user - start.children_user
        sidecar["children_cpu_sys_s"] = end.children_system - start.children_system
        sidecar["maxrss_kb"] = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
        if profiler is not None:
            profiler.dump_stats(
                str(_session.run_dir / "proc" / sidecar["profile_file"])
            )
        sidecar["complete"] = True
        sidecar["exit_path"] = exit_path
        _write_sidecar(segment)
    except OSError as error:
        _disable(f"cannot write segment {segment['name']}: {error}")
    finally:
        _session.closing = False
    if _session.pending_signal is not None:
        _terminate(_session.pending_signal)


@contextlib.contextmanager
def profile_segment(
    stage: str, tags: Mapping[str, str] | None = None
) -> Iterator[None]:
    """Profile the block as its own segment tagged ``stage``, then resume the previous one.

    A no-op when profiling is off. When the open segment already has this stage
    and these tags, the block stays in it (no empty segment is split off).
    """
    tags = dict(tags or {})
    current = _session.segment
    if current is None:
        yield
        return
    previous_stage, previous_tags = (
        current["sidecar"]["stage"],
        current["sidecar"]["tags"],
    )
    if previous_stage == stage and previous_tags == tags:
        yield
        return
    parent = current["sidecar"]["parent_segment"]
    try:
        _close_segment("segment-end")
        if _session.result:
            _open_segment(stage, tags, parent)
    except OSError as error:
        _disable(f"cannot open segment {stage}: {error}")
    try:
        yield
    finally:
        try:
            if _session.segment is not None:
                _close_segment("segment-end")
            if _session.result and not _session.warned:
                _open_segment(previous_stage, previous_tags, parent)
        except OSError as error:
            _disable(f"cannot resume segment {previous_stage}: {error}")


# ---------------------------------------------------------------------------
# Exit paths and fork hooks
# ---------------------------------------------------------------------------


def _at_exit() -> None:
    _close_segment("atexit")
    if _session.root and _session.pid == os.getpid() and _session.run_dir is not None:
        try:
            _write_run_json(time.time())
        except OSError as error:
            _disable(f"cannot write run.json: {error}")


def _on_sigterm(signum, _frame) -> None:
    """Complete the open segment, then terminate with the default SIGTERM action.

    When the signal interrupts a segment that is being closed (e.g. a pool
    worker finishing its exit while Pool.terminate signals it), that close
    completes first and re-delivers the signal itself.
    """
    signal.signal(signum, signal.SIG_IGN)
    if _session.closing:
        _session.pending_signal = signum
        return
    _close_segment("sigterm")
    _terminate(signum)


def _terminate(signum: int) -> None:
    """End this process with the default action of ``signum``."""
    signal.signal(signum, signal.SIG_DFL)
    os.kill(os.getpid(), signum)


def _close_at_mp_exit() -> None:
    _close_segment("mp-finalize")


def _register_mp_finalize(_token) -> None:
    """Run in a multiprocessing child after the fork: complete the segment at the worker's exit."""
    for module_name in ("multiprocessing.util", "multiprocess.util"):
        util = sys.modules.get(module_name)
        if util is not None:
            util.Finalize(None, _close_at_mp_exit, exitpriority=100)


def _after_fork_in_child() -> None:
    """Drop the inherited profiler and open a fresh segment for the forked child."""
    if _session.segment is None:
        return
    inherited = _session.segment["sidecar"]
    if _session.profiler is not None:
        _session.profiler.disable()
        _session.profiler = None
    _session.segment = None
    _session.pid = os.getpid()
    _session.seq = 0
    _session.origin = "fork"
    _session.root = False
    try:
        _open_segment(
            inherited["stage"],
            inherited["tags"],
            f"{inherited['host']}-{inherited['pid']}-{inherited['seq']}",
        )
    except OSError as error:
        _disable(f"cannot open the forked child's segment: {error}")
        return
    for module_name in ("multiprocessing.util", "multiprocess.util"):
        util = sys.modules.get(module_name)
        if util is not None:
            util.register_after_fork(_after_fork_token, _register_mp_finalize)


def _install_exit_paths() -> None:
    atexit.register(_at_exit)
    os.register_at_fork(after_in_child=_after_fork_in_child)
    try:
        if signal.getsignal(signal.SIGTERM) == signal.SIG_DFL:
            signal.signal(signal.SIGTERM, _on_sigterm)
    except ValueError:
        logger.debug("profiling: SIGTERM handler not installed outside the main thread")


# ---------------------------------------------------------------------------
# Session start
# ---------------------------------------------------------------------------


def ensure_profiling_from_env(stage: str | None = None) -> bool:
    """Start profiling this process when CHAMPOLLION_PROFILE is set; idempotent per process."""
    if _session.result is not None:
        return _session.result
    profile_dir = os.environ.get(ENV_PROFILE_DIR)
    if not profile_dir:
        _session.result = False
        return False
    try:
        _session.mode = resolve_mode(os.environ.get(ENV_PROFILE_MODE))
    except InvalidProfileMode as error:
        _disable(f"{ENV_PROFILE_MODE}: {error}")
        _session.result = False
        return False
    try:
        _session.root = not os.environ.get(ENV_PROFILE_RUN)
        if _session.root:
            os.environ[ENV_PROFILE_RUN] = new_run_id()
        _session.run_id = os.environ[ENV_PROFILE_RUN]
        _session.run_dir = Path(profile_dir).absolute() / _session.run_id
        boot = write_boot_dir(_session.run_dir)
        os.environ["PYTHONPATH"] = _prepend_path(
            str(boot), os.environ.get("PYTHONPATH")
        )
        (_session.run_dir / "proc").mkdir(parents=True, exist_ok=True)
        _session.pid = os.getpid()
        _session.t_start = time.time()
        if _session.root:
            _write_run_json(None)
        segment_stage = (
            stage
            or os.environ.get(ENV_PROFILE_STAGE)
            or Path(sys.argv[0] if sys.argv else "").name
        )
        _open_segment(
            segment_stage or "python",
            _parse_tags(os.environ.get(ENV_PROFILE_TAGS)),
            os.environ.get(ENV_PROFILE_PARENT),
        )
    except OSError as error:
        _disable(f"cannot write under {profile_dir}: {error}")
        _session.result = False
        return False
    _install_exit_paths()
    _session.result = True
    logger.debug(
        f"profiling run {_session.run_id} into {_session.run_dir} (mode {_session.mode})"
    )
    return True
